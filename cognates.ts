// Ensemble des faux-amis pour éviter de les marquer comme cognates.
import { isFalseFriend } from "./false-friends";

/**
 * Cherche un cognate pour un mot anglais (insensible à la casse).
 * Exclut les faux-amis (pour éviter les conflits).
 */
export function findCognate(wordEn: string): Cognate | null {
  const w = wordEn.trim().toLowerCase();
  if (!w) return null;
  // Exclut les faux-amis.
  if (isFalseFriend(w)) return null;
  return COGNATES.find((c) => c.en.toLowerCase() === w) ?? null;
}

/** Vrai si le mot anglais est un cognate (facile pour un francophone). */
export function isCognate(wordEn: string): boolean {
  return findCognate(wordEn) !== null;
}
